package com.rfidunlock.app.data

/** Логика срабатывания метки. */
enum class TagMode {
    /**
     * «Присутствие»: поднесение метки → UNLOCK, снятие метки → LOCK.
     * Требует, чтобы приложение было на переднем плане (Reader Mode).
     */
    PRESENCE,

    /**
     * «Переключение»: каждое поднесение метки поочерёдно шлёт LOCK/UNLOCK
     * (первое касание — LOCK, второе — UNLOCK, третье — LOCK и т.д.).
     * Снятие метки игнорируется.
     */
    TOGGLE,
}
