package com.rfidunlock.app.data

/** Текущее состояние ПК для плитки на главном экране. */
enum class PcStatus {
    /** ПК заблокирован (экран блокировки). */
    LOCKED,

    /** ПК разблокирован (сессия активна). */
    UNLOCKED,

    /** ПК недоступен по сети. */
    OFFLINE,

    /** Статус ещё не запрашивался. */
    UNKNOWN,
}
